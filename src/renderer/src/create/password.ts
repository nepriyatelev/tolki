export type RandomSource = (count: number) => Uint32Array

const cryptoRandom: RandomSource = (count) => crypto.getRandomValues(new Uint32Array(count))

export function generatePassword(random: RandomSource = cryptoRandom): string {
  const [a = 0, b = 0, n = 0] = random(3)
  const first = WORDS[a % WORDS.length] ?? WORDS[0]
  let second = WORDS[b % WORDS.length] ?? WORDS[1]
  if (second === first) second = WORDS[(b + 1) % WORDS.length] ?? WORDS[1]
  return `${first}-${second}-${10 + (n % 90)}`
}

/** Random room id for the invite's `r` parameter. */
export function generateRoomId(random: RandomSource = cryptoRandom): string {
  const alphabet = 'abcdefghijkmnpqrstuvwxyz23456789'
  return Array.from(random(10), (v) => alphabet[v % alphabet.length]).join('')
}
